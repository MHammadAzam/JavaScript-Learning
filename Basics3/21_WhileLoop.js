// WHILE LOOP

let i = 0
while (i <= 10) {
     console.log(i)
     i++
}

let myArray = ['flash', 'batman', 'superman']
let j = 0
while(j < myArray.length){
    console.log(myArray[j])
    j++
}


// DO WHILE LOOP
// it runs code one time must then check the condition
let k = 1
do {
   console.log(k)
   k++
} while (k <= 10);